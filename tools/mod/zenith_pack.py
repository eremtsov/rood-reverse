#!/usr/bin/env python3
"""Pack the sections of the Zenith build of src/mod/wswap.c into the unreferenced code ranges.

    python3 -I tools/mod/zenith_pack.py SECTIONS BINS OUT.ld

SECTIONS  `objdump -h wswap.o | awk '$2 ~ /^\\./ {print $2, $3}'` of the Zenith build (name size-in-hex per line)
BINS      tools/mod/zenith_bins.txt: `name start size tier note`; tier 0 = ranges the vanilla mod already used, 1 = further
          unreferenced BATTLE.PRG functions, 2 = unreferenced SLUS_010.40 library modules (see docs/zenith-edition)
OUT.ld    the linker script (wswap-zenith.ld).

The packing is an exhaustive depth-first search (items largest first, ranges tried cheapest tier first, then best fit), so
the result is deterministic. It prefers tier 0, then 1, then 2, and drops every range it does not need.
Every `.z_*` section is a function or table of the mod; `.text` is the first function (migrate); `.bss` is the mod's state,
which gets an output section of its own with a LONG(0) so that objcopy emits the zeros.
"""
import sys

secs_file, bins_file, out_file = sys.argv[1:4]
items = []
for l in open(secs_file):
    p = l.split()
    if len(p) != 2:
        continue
    n, sz = p[0], int(p[1], 16)
    if not (n.startswith('.z_') or n in ('.text', '.bss')) or sz == 0:
        continue
    if n == '.bss':
        sz += 4                         # the LONG(0)
    items.append((n, (sz + 3) & ~3))
items.sort(key=lambda x: (-x[1], x[0]))

bins = []
for l in open(bins_file):
    l = l.strip()
    if not l or l.startswith('#'):
        continue
    p = l.split(None, 4)
    bins.append({'name': p[0], 'start': int(p[1], 16), 'size': int(p[2]), 'tier': int(p[3]), 'note': p[4] if len(p) > 4 else ''})

sys.setrecursionlimit(10000)
nodes = [0]


def solve(allowed):
    allowed = sorted(allowed)
    free = {i: bins[i]['size'] for i in allowed}
    result = []
    nodes[0] = 0

    def dfs(k):
        nodes[0] += 1
        if nodes[0] > 2_000_000:
            return False
        if k == len(items):
            return True
        n, sz = items[k]
        tried = set()
        # cheapest tier first; within a tier ranges that are already in use before empty ones, then the tightest fit
        cands = sorted((i for i in allowed if free[i] >= sz),
                       key=lambda i: (bins[i]['tier'], free[i] == bins[i]['size'], free[i] - sz))
        for i in cands:
            key = (free[i], bins[i]['tier'], free[i] == bins[i]['size'])
            if key in tried:
                continue
            tried.add(key)
            free[i] -= sz
            result.append((n, i))
            if dfs(k + 1):
                return True
            result.pop()
            free[i] += sz
        return False

    return list(result) if dfs(0) else None


allowed = set(range(len(bins)))
best = solve(allowed)
if not best:
    sys.exit('no packing found: %d bytes of sections' % sum(s for _, s in items))
# drop the ranges that are not needed: tier 2 first (SLUS_010.40), then tier 1, largest first; keep dropping while it still fits
for tier in (2, 1):
    for i in sorted((i for i in allowed if bins[i]['tier'] == tier), key=lambda i: -bins[i]['size']):
        trial = allowed - {i}
        r = solve(trial)
        if r:
            allowed, best = trial, r
# the tier-0 ranges are free to use; use only what is needed for the rest
for i in sorted((i for i in allowed if bins[i]['tier'] == 0), key=lambda i: bins[i]['size']):
    trial = allowed - {i}
    r = solve(trial)
    if r:
        allowed, best = trial, r

by_bin = {}
for n, i in best:
    by_bin.setdefault(i, []).append(n)
sz = dict(items)
lines = ['/* Generated by tools/mod/zenith_pack.py from tools/mod/zenith_bins.txt and the sections of the Zenith build of',
         ' * src/mod/wswap.c; do not edit by hand. Every output section is placed at the start of a range of unreferenced code of',
         ' * BATTLE.PRG (tier 0/1) or SLUS_010.40 (tier 2) and must fit in it (tools/mod/build_zenith.sh checks that and that the',
         ' * bytes it overwrites are the original ones). */',
         'ENTRY(wswap_entry)', 'SECTIONS', '{']
tot = 0
for i in sorted(by_bin, key=lambda i: bins[i]['start']):
    b = bins[i]
    used = sum(sz[n] for n in by_bin[i])
    tot += used
    outn = '.zb_%08X' % b['start']
    body = []
    for n in sorted(by_bin[i], key=lambda n: (-sz[n], n)):
        if n == '.bss':
            body.append('*(.bss*) *(COMMON) LONG(0);')
        else:
            body.append('*(%s)' % n)
    lines.append('    /* %-12s %08X..%08X %4d of %4d bytes (tier %d): %s */' % (b['name'], b['start'], b['start'] + b['size'], used, b['size'], b['tier'], ', '.join(by_bin[i])))
    lines.append('    . = 0x%08X;' % b['start'])
    lines.append('    %s : SUBALIGN(4) { %s }' % (outn, ' '.join(body)))
lines.append('    /DISCARD/ : { *(.reginfo) *(.MIPS.abiflags) *(.pdr) *(.gnu.attributes) *(.comment) *(.mdebug*) *(.data) }')
lines.append('}')
open(out_file, 'w').write('\n'.join(lines) + '\n')
print('%d sections (%d bytes) in %d ranges (tier 0: %d, tier 1: %d, tier 2: %d)' % (
    len(items), tot, len(by_bin), *[sum(1 for i in by_bin if bins[i]['tier'] == t) for t in (0, 1, 2)]))
for i in sorted(by_bin, key=lambda i: bins[i]['start']):
    b = bins[i]
    print('  %08X tier %d %4d/%4d  %s' % (b['start'], b['tier'], sum(sz[n] for n in by_bin[i]), b['size'], ' '.join(by_bin[i])))
